# Parent configurations
configs = list(product(range(3), repeat=3))

# Probability of a match = P(decision=1) * P(decision_o=1)
# Assuming conditional independence given the parents.
p_match = decision[:, 1] * decision_o[:, 1]

df = pd.DataFrame(configs, columns=[
    "demographic", "perceptions", "preferences"
])
df["p_match"] = p_match

# Calculate average match probability for each value of each parent
results = {}

for parent in ["demographic", "perceptions", "preferences"]:
    means = df.groupby(parent)["p_match"].mean()

    results[parent] = {
        "conditional_means": means.to_dict(),
        "range": means.max() - means.min(),
        "std": means.std()
    }

# Normalize ranges to obtain relative influence scores
total = sum(r["range"] for r in results.values())

for parent, r in results.items():
    r["influence"] = r["range"] / total if total > 0 else 0

# Display
for parent, r in results.items():
    print(f"\n{parent.upper()}")
    print("Mean match probability by value:", r["conditional_means"])
    print(f"Range: {r['range']:.4f}")
    print(f"Std: {r['std']:.4f}")
    print(f"Relative influence: {100*r['influence']:.2f}%")